  static String t(BuildContext context, String key) {
    final code = Localizations.localeOf(context).languageCode;
    return _s[code]?[key] ?? _s['en']![key] ?? key;
  }

  // Returns FA string when locale is FA, EN otherwise
  static String meaning(BuildContext context,
      {required String fa, required String en}) {
    return Localizations.localeOf(context).languageCode == 'fa' ? fa : en;
  }

  /// True, wenn die aktive Zweitsprache Farsi ist (Quelle: Settings-Locale).
  /// فاز L: تنها منبع تشخیص زبان — هیچ state محلی (_showFa) مجاز نیست.
  static bool isFa(BuildContext context) =>
      Localizations.localeOf(context).languageCode == 'fa';

  /// Aktive Sprache ohne BuildContext (Services/Notifications).
  /// Wird in app.dart bei jedem Locale-Wechsel gesetzt.
  static String activeLang = 'fa';

  /// Statische Übersetzung ohne context (Services).
  static String ts(String key) =>
      _s[activeLang]?[key] ?? _s['en']![key] ?? key;

  /// Liest `<base>_en` im EN-Modus aus einer JSON-Map, Fallback `<base>_fa`.
  /// فاز L3 — Standard für alle Content-JSON-Reads in Screens.
  static String loc(BuildContext context, Map<String, dynamic> m, String base) =>
      isFa(context)
          ? (m['${base}_fa'] as String? ?? '')
          : (m['${base}_en'] as String? ??
              m['${base}_fa'] as String? ??
              '');

  /// t() mit {platzhalter}-Ersetzung: tf(ctx,'x_of_y',{'x':'3','y':'10'})
  static String tf(BuildContext context, String key, Map<String, String> args) {
    var out = t(context, key);
    args.forEach((k, v) => out = out.replaceAll('{$k}', v));
    return out;
  }

